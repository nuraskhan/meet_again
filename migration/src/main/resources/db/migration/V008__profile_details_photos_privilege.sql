-- A fuller profile: more about the person, several photos, and the privilege level that later
-- becomes the subscription plan.

-- 1. The privilege level of a person. Everyone starts at STANDARD. Nobody can change their own:
--    it is not part of what a profile update accepts. What a level allows is in the enum Privilege.
alter table profile add column privilege text not null default 'STANDARD'
  check (privilege in ('STANDARD', 'PRO', 'MAX'));

-- 2. More about the person. All optional.
alter table profile add column occupation text;
alter table profile add column education  text;
alter table profile add column hometown   text;
alter table profile add column pronouns   text;
alter table profile add column languages  text;

-- 3. Interests: short labels, in the order the person put them.
create table profile_interest (
  id              bigint generated by default as identity primary key,
  user_account_id bigint  not null references user_account,
  position        integer not null check (position >= 1),
  label           text    not null,
  unique (user_account_id, position)
);

-- 4. Prompts: a question the person chose and their answer to it.
create table profile_prompt (
  id              bigint generated by default as identity primary key,
  user_account_id bigint  not null references user_account,
  position        integer not null check (position >= 1),
  question        text    not null,
  answer          text    not null,
  unique (user_account_id, position)
);

-- 5. Photos, several per person, in the person's order. Position 1 is the main one: it is the
--    picture shown next to the name everywhere (profile.avatar_url is its address).
--    The order is unique per person, checked at the end of the transaction - so photos can swap
--    places inside one.
create table profile_photo (
  id              bigint generated by default as identity primary key,
  user_account_id bigint      not null references user_account,
  position        integer     not null check (position >= 1),
  token           text        not null unique,
  content_type    text        not null check (content_type in ('image/jpeg', 'image/png')),
  content         bytea       not null,
  created_at      timestamptz not null,
  constraint profile_photo__order unique (user_account_id, position) deferrable initially deferred
);

-- The single picture a person had becomes their first photo, at a new address.
insert into profile_photo (user_account_id, position, token, content_type, content, created_at)
select user_account_id, 1, token, content_type, content, updated_at
from avatar;

update profile
set avatar_url = replace(avatar_url, '/public/avatar/', '/public/photo/')
where avatar_url is not null;

drop table avatar;

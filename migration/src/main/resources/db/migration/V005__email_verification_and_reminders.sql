-- E-mail: confirming an address, and reminders about upcoming events.

-- 1. Is the address confirmed. Empty = not yet. Existing accounts start unconfirmed.
alter table user_account add column email_verified_at timestamptz;

-- 2. A link sent to confirm an address. Only the hash of its token is kept: whoever reads this
--    table cannot confirm somebody's address with it.
create table email_verification (
  id              bigint generated by default as identity primary key,
  user_account_id bigint      not null references user_account,
  token_hash      text        not null unique,
  created_at      timestamptz not null,
  expires_at      timestamptz not null,
  used_at         timestamptz
);

create index email_verification__user on email_verification (user_account_id, created_at);

-- 3. The time zone the dates of an event are meant in (IANA name, e.g. America/New_York), taken
--    from the creator's browser. A reminder shows the time in it. Empty for events made before.
alter table event add column time_zone text;

-- 4. A reminder sent (or being sent) to one person about one event. The unique pair is what keeps
--    a reminder from going out twice.
create table event_reminder (
  id              bigint generated by default as identity primary key,
  event_id        bigint      not null references event,
  user_account_id bigint      not null references user_account,
  sent_at         timestamptz not null,
  unique (event_id, user_account_id)
);

-- Places to go, and the places suggested for an event.

-- 1. A place people can meet at. Its category is one of the event types: a suggestion for a
--    "COFFEE" event is looked for among "COFFEE" places.
create table place (
  id             bigint generated by default as identity primary key,
  name           text             not null,
  category       text             not null
    check (category in ('BATH', 'FOOD', 'COFFEE', 'BAR', 'WALK', 'CINEMA', 'SPORT',
                        'BOARD_GAMES', 'OTHER')),
  description    text,
  address        text             not null,
  latitude       double precision not null check (latitude between -90 and 90),
  longitude      double precision not null check (longitude between -180 and 180),
  -- How good the place is, 0 to 5. Among places that suit, the higher is suggested first.
  rating         double precision not null check (rating between 0 and 5),
  -- Expected spending per person, in the same units as the budget of an event.
  price_min      integer          not null,
  price_max      integer          not null,
  website        text,
  phone          text,
  -- Invented for demonstration, not a real business. Lets them be told apart and removed.
  sample         boolean          not null default false,
  created_at     timestamptz      not null,
  deactivated_at timestamptz, -- filled = no longer suggested
  check (0 <= price_min and price_min <= price_max)
);

-- Suggestions search by category inside a box of coordinates.
create index place__search on place (category, latitude, longitude);

-- 2. The places suggested for an event, best first. Computed once and kept: opening the event
--    shows these rows; asking again replaces them.
create table event_suggestion (
  id                      bigint generated by default as identity primary key,
  event_id                bigint           not null references event,
  place_id                bigint           not null references place,
  rank                    integer          not null check (rank >= 1),
  -- Miles from the people whose location was known, at the moment of computing.
  average_distance_mi     double precision not null,
  farthest_distance_mi    double precision not null,
  -- Every one of those people is within their own travel radius of the place.
  within_everyones_reach  boolean          not null,
  -- The prices of the place overlap the budget of the event.
  fits_budget             boolean          not null,
  -- How many people's locations the computing was based on.
  participants_considered integer          not null,
  created_at              timestamptz      not null,
  unique (event_id, rank),
  unique (event_id, place_id)
);

-- 3. When suggestions were last computed for the event. Empty = never; filled with no rows in
--    event_suggestion = computed, and nothing suitable was found.
alter table event add column suggested_at timestamptz;

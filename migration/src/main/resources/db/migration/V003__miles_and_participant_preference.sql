-- Distances are in miles everywhere (US units), and every guest of an event says where they are
-- and how far they are ready to travel.

-- 1. The preferred distance of an event: kilometres -> miles. Existing values are converted and
--    rounded; rounding keeps min <= max.
alter table event rename column distance_min_km to distance_min_mi;
alter table event rename column distance_max_km to distance_max_mi;

update event
set distance_min_mi = round(distance_min_mi * 0.621371),
    distance_max_mi = round(distance_max_mi * 0.621371);

-- 2. What a guest tells about themselves for one event. One row per guest per event.
--    The place is either coordinates (from the device, with the person's permission) or a text the
--    person typed; at least one of the two.
create table participant_preference (
  id               bigint generated by default as identity primary key,
  event_id         bigint      not null references event,
  user_account_id  bigint      not null references user_account,
  latitude         double precision,
  longitude        double precision,
  location_text    text,
  travel_radius_mi integer     not null check (travel_radius_mi between 1 and 500),
  updated_at       timestamptz not null,
  unique (event_id, user_account_id),
  check ((latitude is null) = (longitude is null)),
  check (latitude is not null or location_text is not null),
  check (latitude between -90 and 90),
  check (longitude between -180 and 180)
);

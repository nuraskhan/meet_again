-- MVP: users, profiles, friends, events with invitations, group chats.
--
-- Conventions (CLAUDE.md, "Database"): singular table names, references `<table>_id` and
-- `<role>__<table>_id`, moments as timestamptz. Nothing is deleted physically: a row gets a status
-- or a "..._at" moment instead.

create table user_account (
  id             bigint generated by default as identity primary key,
  email          text        not null unique, -- stored in lower case
  password_hash  text        not null,
  created_at     timestamptz not null,
  deactivated_at timestamptz
);

create table profile (
  user_account_id bigint primary key references user_account,
  display_name    text        not null,
  bio             text,
  city            text,
  birth_date      date,
  avatar_url      text,
  updated_at      timestamptz not null
);

-- One row per friend request. ACCEPTED = they are friends.
create table friendship (
  id                         bigint generated by default as identity primary key,
  requester__user_account_id bigint      not null references user_account,
  addressee__user_account_id bigint      not null references user_account,
  status                     text        not null
    check (status in ('PENDING', 'ACCEPTED', 'DECLINED', 'REMOVED')),
  created_at                 timestamptz not null,
  responded_at               timestamptz,
  check (requester__user_account_id <> addressee__user_account_id)
);

-- Between two people there is at most one live (pending or accepted) row, in either direction.
create unique index friendship__live_pair on friendship (
  least(requester__user_account_id, addressee__user_account_id),
  greatest(requester__user_account_id, addressee__user_account_id)
) where status in ('PENDING', 'ACCEPTED');

create index friendship__addressee on friendship (addressee__user_account_id);

create table chat (
  id         bigint generated by default as identity primary key,
  title      text        not null,
  created_at timestamptz not null
);

create table chat_member (
  id              bigint generated by default as identity primary key,
  chat_id         bigint      not null references chat,
  user_account_id bigint      not null references user_account,
  joined_at       timestamptz not null,
  left_at         timestamptz, -- filled = no longer in the chat
  unique (chat_id, user_account_id)
);

create index chat_member__user on chat_member (user_account_id);

create table chat_message (
  id                      bigint generated by default as identity primary key,
  chat_id                 bigint      not null references chat,
  author__user_account_id bigint      not null references user_account,
  text                    text        not null,
  created_at              timestamptz not null
);

create index chat_message__chat on chat_message (chat_id, id);

-- An invitation form filled by its creator. Every event has its own group chat.
create table event (
  id                       bigint generated by default as identity primary key,
  creator__user_account_id bigint      not null references user_account,
  chat_id                  bigint      not null references chat,
  event_type               text        not null
    check (event_type in ('BATH', 'FOOD', 'COFFEE', 'BAR', 'WALK', 'CINEMA', 'SPORT',
                          'BOARD_GAMES', 'OTHER')),
  title                    text        not null,
  description              text,
  distance_min_km          integer     not null,
  distance_max_km          integer     not null,
  price_min                integer     not null,
  price_max                integer     not null,
  starts_at                timestamptz,
  status                   text        not null check (status in ('ACTIVE', 'CANCELLED')),
  created_at               timestamptz not null,
  check (0 <= distance_min_km and distance_min_km <= distance_max_km),
  check (0 <= price_min and price_min <= price_max)
);

create index event__creator on event (creator__user_account_id);

create table invitation (
  id                       bigint generated by default as identity primary key,
  event_id                 bigint      not null references event,
  invitee__user_account_id bigint      not null references user_account,
  status                   text        not null check (status in ('PENDING', 'ACCEPTED', 'DECLINED')),
  created_at               timestamptz not null,
  responded_at             timestamptz,
  unique (event_id, invitee__user_account_id)
);

create index invitation__invitee on invitation (invitee__user_account_id);

-- An event can be opened by a link, and offers several dates instead of one.

-- 1. The link. The token is the secret part of the address: whoever has it can see the event and,
--    after registering, join it. Existing events get one too.
alter table event add column share_token text;

update event set share_token = replace(gen_random_uuid()::text, '-', '');

alter table event alter column share_token set not null;

create unique index event__share_token on event (share_token);

-- 2. Proposed dates. Zero rows = "to be agreed in the chat".
create table event_time_option (
  id        bigint generated by default as identity primary key,
  event_id  bigint      not null references event,
  starts_at timestamptz not null,
  unique (event_id, starts_at)
);

-- The single date an event had becomes its only proposed date.
insert into event_time_option (event_id, starts_at)
select id, starts_at
from event
where starts_at is not null;

alter table event drop column starts_at;

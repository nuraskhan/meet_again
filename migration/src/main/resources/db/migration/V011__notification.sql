-- Notifications: what happened that a person should know about. Written by the server when it
-- happens, pushed to the person's open pages at once, and kept so it can be read later.

create table notification (
  id                     bigint generated by default as identity primary key,
  -- Whom it is for.
  user_account_id        bigint      not null references user_account,
  kind                   text        not null
    check (kind in ('FRIEND_REQUEST', 'FRIEND_ACCEPTED', 'EVENT_INVITATION', 'INVITATION_ACCEPTED',
                    'INVITATION_DECLINED', 'GUEST_JOINED', 'GUEST_LEFT', 'REMOVED_FROM_EVENT',
                    'EVENT_CANCELLED')),
  -- Who did it; empty when nobody in particular did.
  actor__user_account_id bigint references user_account,
  -- The event it is about; empty when it is not about an event.
  event_id               bigint references event,
  -- The sentence shown to the person, as it read when the thing happened.
  text                   text        not null,
  created_at             timestamptz not null,
  read_at                timestamptz -- empty = not read yet
);

-- A person's notifications, newest first.
create index notification__recipient on notification (user_account_id, id desc);

-- "How many have I not read" is asked on every page.
create index notification__unread on notification (user_account_id) where read_at is null;

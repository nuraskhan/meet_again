-- Three things: a person's calendar of availability, what a reliability rating is counted from,
-- and a venue attached to an event.

-- 1. Availability: days a person marks in their calendar.
--      BUSY - not available these days;
--      FREE - free these days ("invite me");
--      TRIP - away in another city (the city is said).
--    Whole days, as the person means them: a date has no time zone, so "the 5th" is the 5th for
--    everyone who looks. Friends see the kind, the days and the city - never the note.
create table availability (
  id              bigint generated by default as identity primary key,
  user_account_id bigint      not null references user_account,
  kind            text        not null check (kind in ('BUSY', 'FREE', 'TRIP')),
  from_date       date        not null,
  to_date         date        not null, -- the last day, included
  city            text,                 -- where to, for a TRIP
  note            text,                 -- for the person alone
  created_at      timestamptz not null,
  deleted_at      timestamptz,          -- filled = removed by the person
  check (from_date <= to_date)
);

-- "What has this person marked around these days."
create index availability__user on availability (user_account_id, from_date) where deleted_at is null;

-- 2. Reliability: did the person do what they said they would.
--    left_at  - they said "coming" and then left while the event was still on;
--    no_show  - they said "coming", stayed in, and the creator marked afterwards that they
--               did not come.
alter table invitation add column left_at timestamptz;
alter table invitation add column no_show boolean not null default false;

-- 3. Venues. The table "place" is the venue; it gains where it is from and which city it is in,
--    and an event can have one attached.
alter table place add column city text;            -- "Astana", "Almaty"
alter table place add column source text;          -- where the record came from: "2GIS"; empty = by hand
alter table place add column external_id text;     -- its id at the source: loading again updates, never doubles
alter table place add column review_count integer; -- how many reviews the rating rests on; empty = unknown

create unique index place__external on place (source, external_id) where external_id is not null;

-- The venue the creator chose for the event; empty = not chosen.
alter table event add column place_id bigint references place;

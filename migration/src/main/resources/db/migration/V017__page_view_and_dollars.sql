-- Two unrelated things that ship together: counting visits, and prices in dollars.

-- 1. Visits to the site, for the page /admin/analytica.
--    One row per page opened. Deliberately little is kept:
--      visitor_id - a random id the page makes up and keeps in the browser; it tells two visits of
--                   one browser from visits of two, and says nothing about who the person is;
--      path       - the PATTERN of the page ("/plans/:eventId"), never the address itself: an
--                   address can carry a secret (the token of an invitation link);
--      user_account_id - who was signed in, if anyone.
--    No IP address, no browser details.
create table page_view (
  id              bigint generated by default as identity primary key,
  visitor_id      text        not null,
  user_account_id bigint references user_account,
  path            text        not null,
  created_at      timestamptz not null
);

-- The page of analytics reads a stretch of days.
create index page_view__created on page_view (created_at);

-- 2. Prices are in US dollars now; until now they were in tenge.
--    WHY 250: the default budgets were rewritten by that factor (a bathhouse: 5000-15000 became
--    20-60), so the same factor keeps every existing plan and place where it stood relative to
--    them. It is a change of scale for demonstration data, not an exchange rate.
update event
set price_min = round(price_min / 250.0),
    price_max = round(price_max / 250.0);

update place
set price_min = round(price_min / 250.0),
    price_max = round(price_max / 250.0)
where price_min is not null;
